def _graph_to_csr(G):
    """networkx graph -> symmetric binary CSR adjacency with zero diagonal."""
    G = nx.Graph(G)  # drop directionality / multiedges
    A = nx.to_scipy_sparse_array(G, nodelist=list(G.nodes()), format="csr", dtype=float)
    A = A.maximum(A.T)
    A.setdiag(0)
    A.eliminate_zeros()
    A.data = np.ones_like(A.data)
    return A


BUILTIN_DATASETS = {
    # No data files ship with this package: both graphs come from networkx.
    "zachary": (nx.karate_club_graph, "karate_club"),
    "florentine": (nx.florentine_families_graph, "florentine_families"),
}


def load_dataset(name):
    """Resolve a built-in named dataset to (adjacency, label).

    The built-ins are generated by networkx (no data file is shipped or read).
    For any other network, pass --input PATH instead.
    """
    try:
        ctor, label = BUILTIN_DATASETS[name]
    except KeyError:
        raise ValueError(
            f"Unknown named dataset '{name}'. Built-ins: {sorted(BUILTIN_DATASETS)}; "
            f"use --input PATH for your own graph."
        ) from None
    return _graph_to_csr(ctor()), label


