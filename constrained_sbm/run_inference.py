def run_gibbs(A, args, directed):
    n = A.shape[0]
    E = num_directed_edges(A) if directed else num_undirected_edges(A)
    beta_arg = None if args.infer_beta else args.beta

    print(f"\nFitting CONSTRAINED Gibbs (game-theoretic), K={args.K} ...")
    con = fit_gibbs(
        A, K=args.K, beta=beta_arg, infer_beta=args.infer_beta,
        degree_corrected=args.degree_corrected, theta_max=args.theta_max,
        n_samples=args.n_samples, burn_in=args.burn_in, thin=args.thin,
        n_chains=args.n_chains, seed=args.seed, verbose=args.verbose,
        gauge=args.gauge, directed=directed,
    )
    print(f"  done (MH accept rate = {con['acceptance_rate']:.3f})")
    print(f"Fitting FREE Gibbs (unconstrained B), K={args.K} ...")
    free = fit_free_gibbs(
        A, K=args.K, degree_corrected=args.degree_corrected, theta_max=args.theta_max,
        n_samples=args.n_samples, burn_in=args.burn_in, thin=args.thin,
        n_chains=args.n_chains, seed=args.seed, verbose=args.verbose,
        directed=directed,
    )
    print("  done")

    _print_constrained_block(con, args.K, args.infer_beta)
    _print_posterior_summary(con, K=args.K)

    n_payoffs = len(con.get("rhat_payoffs") or [])
    payoff_labels = (["c", "b"] if (args.K == 2 and n_payoffs == 2)
                     else [f"payoff[{i}]" for i in range(n_payoffs)])
    _print_mcmc_diagnostics("CONSTRAINED", con, payoff_labels,
                            "rhat_payoffs", "ess_payoffs", show_acceptance=True)
    _print_mcmc_diagnostics("FREE", free, free.get("B_param_labels", []),
                            "rhat_B", "ess_B", show_acceptance=False)

    # WAIC over the dyad-level pointwise log-likelihood.
    print("\nComputing pointwise log-likelihood + WAIC ...")
    ll_con = pointwise_loglik_constrained(A, con)
    ll_free = pointwise_loglik_free(A, free)
    waic_con = waic_from_loglik(ll_con)
    waic_free = waic_from_loglik(ll_free)
    cmp_waic = compare_waic(waic_con, waic_free, "constrained", "free")
    print("\n=== WAIC (lower is better) ===")
    print(f"  {'':16s}  {'lppd':>12s}  {'p_WAIC':>10s}  {'WAIC':>12s}  {'SE':>8s}")
    for nm, w in (("constrained", waic_con), ("free", waic_free)):
        print(f"  {nm:16s}  {w['lppd']:12.2f}  {w['p_waic']:10.2f}  "
              f"{w['waic']:12.2f}  {w['se_waic']:8.2f}")
    print(f"  ΔWAIC (constrained − free) = {cmp_waic['delta_waic']:+.2f}")
    print(f"  Akaike weights: P(constrained)≈{cmp_waic['weight_constrained']:.4f}  "
          f"P(free)≈{cmp_waic['weight_free']:.4f}")
    print(f"  Verdict: WAIC prefers the {cmp_waic['preferred'].upper()} model.")

    # PSIS-LOO-CV (requires arviz; degrade gracefully if absent).
    loo_payload = None
    print("\nComputing PSIS-LOO-CV (arviz) ...")
    try:
        n_chains = int(con.get("n_chains", args.n_chains))
        loo_con = loo_from_loglik(ll_con, n_chains=n_chains)
        loo_free = loo_from_loglik(ll_free, n_chains=n_chains)
        cmp_loo = compare_loo(loo_con, loo_free, "constrained", "free")
        print("\n=== PSIS-LOO-CV (LOOIC: lower is better) ===")
        print(f"  {'':16s}  {'elpd_loo':>12s}  {'SE':>8s}  {'p_loo':>10s}  {'LOOIC':>12s}")
        for nm, l in (("constrained", loo_con), ("free", loo_free)):
            print(f"  {nm:16s}  {l['elpd_loo']:12.2f}  {l['se_elpd_loo']:8.2f}  "
                  f"{l['p_loo']:10.2f}  {l['looic']:12.2f}")
        print(f"  ΔLOOIC (constrained − free) = {cmp_loo['delta_looic']:+.2f}")
        print(f"  Akaike weights: P(constrained)≈{cmp_loo['weight_constrained']:.4f}  "
              f"P(free)≈{cmp_loo['weight_free']:.4f}")
        print(f"  Verdict: PSIS-LOO-CV prefers the {cmp_loo['preferred'].upper()} model.")
        loo_payload = cmp_loo
    except ImportError:
        print("  [skipped: arviz not installed. Install with `pip install -e \".[loo]\"` or `pip install arviz`]")

    payload = {
        "method": "gibbs", "K": args.K, "n": int(n), "num_edges": int(E),
        "directed": bool(directed),
        "constrained": {
            "payoff_matrix": con["payoff_matrix"].tolist(),
            "freqs": np.asarray(con["freqs"]).tolist(),
            "beta": con["beta"], "M": con["M"].tolist(), "B": con["B"].tolist(),
            "rhat_payoffs": list(con.get("rhat_payoffs") or []),
            "ess_payoffs": list(con.get("ess_payoffs") or []),
        },
        "waic": {"delta_waic": cmp_waic["delta_waic"], "preferred": cmp_waic["preferred"]},
        "loo": loo_payload,
    }
    if args.K == 2:
        payload["constrained"].update(b=con["b"], c=con["c"], x=con["x"])
    return payload


# --------------------------------------------------------------------------- #
# CLI                                                                         #
# --------------------------------------------------------------------------- #
def main(argv=None):
    p = argparse.ArgumentParser(
        description="Fit the constrained game-theoretic SBM and compare it to a free SBM.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    src = p.add_mutually_exclusive_group(required=True)
    src.add_argument("--dataset", choices=sorted(BUILTIN_DATASETS),
                     help="Built-in named dataset generated by networkx (no file needed).")
    src.add_argument("--input", help="Graph file: edgelist, .npz, or .graphml/.gml")

    p.add_argument("--method", choices=["em", "gibbs"], default="em",
                   help="Estimator. 'em' (default) or 'gibbs'.")
    p.add_argument("--K", type=int, default=2, help="Number of blocks. Default 2.")
    p.add_argument("--beta", type=float, default=3.0, help="Inverse temperature (default 3.0).")
    p.add_argument("--infer-beta", action="store_true", help="Infer/sample β instead of fixing it.")
    p.add_argument("--gauge", choices=["row_sum", "pin_diag"], default=None,
                   help="Gauge fix. Default: row_sum for K=2, pin_diag for K>=3.")
    p.add_argument("--degree-corrected", action="store_true",
                   help="Enable per-node degree correction (Poisson DC-SBM).")
    p.add_argument("--directed", choices=["auto", "yes", "no"], default="auto",
                   help="Directed or undirected fit. 'auto' (default) inspects the loaded "
                        "adjacency: directed if asymmetric. 'no' symmetrizes the input.")
    p.add_argument("--canonicalize", action=argparse.BooleanOptionalAction, default=True,
                   help="K=2 pin_diag, EM only: report the orientation with c/b <= a/d "
                        "(X = more homophilous block). --no-canonicalize reports the raw fit.")
    p.add_argument("--theta-max", type=float, default=100.0,
                   help="Upper clip on per-node degree parameters theta in DC mode "
                        "(EM; for Gibbs it applies to the EM initialisation only).")
    p.add_argument("--seed", type=int, default=42, help="Random seed (default 42).")
    p.add_argument("--out-json", type=str, default=None, help="Write the full report as JSON.")
    p.add_argument("--verbose", action="store_true", help="Print per-iteration progress.")

    em = p.add_argument_group("EM options (--method em)")
    em.add_argument("--restarts", type=int, default=10, help="Random restarts; the best-ELBO fit is kept (default 10).")
    em.add_argument("--max-iter", type=int, default=200, help="Maximum EM iterations per restart.")
    em.add_argument("--tol", type=float, default=1e-6, help="Relative ELBO change for convergence.")
    em.add_argument("--n-spectral", type=int, default=1,
                    help="Seed the first N restarts from N distinct low Laplacian eigenvectors "
                         "(then one k-means, then random). Default 1. The paper uses 4.")
    em.add_argument("--beta-sweep", action="store_true",
                    help="Search beta in [--beta-low, --beta-high] for the maximum ELBO "
                         "(Brent's method, ~10-15 EM fits) instead of fixing --beta.")
    em.add_argument("--beta-low", type=float, default=0.5, help="Lower bound for --beta-sweep.")
    em.add_argument("--beta-high", type=float, default=10.0, help="Upper bound for --beta-sweep.")
    em.add_argument("--cv-folds", type=int, default=0,
                    help="If >0, run k-fold CV and report ΔELPD (constrained − free).")

    gi = p.add_argument_group("Gibbs options (--method gibbs)")
    gi.add_argument("--n-samples", type=int, default=1500, help="Post-burn-in samples per chain.")
    gi.add_argument("--burn-in", type=int, default=750, help="Burn-in iterations per chain.")
    gi.add_argument("--thin", type=int, default=2, help="Keep every k-th sample.")
    gi.add_argument("--n-chains", type=int, default=2, help="Independent chains (for R-hat).")

    args = p.parse_args(argv)
    if args.beta_sweep and args.infer_beta:
        p.error("--beta-sweep and --infer-beta are mutually exclusive.")
    if args.beta_sweep and args.method == "gibbs":
        p.error("--beta-sweep is EM-only; use --infer-beta with --method gibbs.")

    if args.dataset:
        A, label = load_dataset(args.dataset)
    else:
        A = load_graph(args.input, symmetrize=False)
        label = args.input
    directed, banner = resolve_directed_mode(A, args.directed)
    if not directed:
        A = A.maximum(A.T)  # undirected fit: an arc in either direction is one edge
        A.setdiag(0)
        A.eliminate_zeros()
        A.data = np.ones_like(A.data)
    if args.cv_folds > 0 and directed:
        p.error("--cv-folds (edge-holdout CV) is only implemented for undirected fits.")

    n = A.shape[0]
    if directed:
        E = num_directed_edges(A)
        density = E / max(n * (n - 1), 1)
        edge_kind = "directed"
    else:
        E = num_undirected_edges(A)
        density = 2 * E / max(n * (n - 1), 1)
        edge_kind = "undirected"
    print(f"Dataset: {label}")
    print(banner)
    print(f"  n={n} nodes, |E|={E} {edge_kind} edges, density={density:.4g}")
    beta_desc = "sweep" if args.beta_sweep else ("inferred" if args.infer_beta else args.beta)
    print(f"  K={args.K}, method={args.method}, beta={beta_desc}")

    if args.method == "em":
        payload = run_em(A, args, directed)
    else:
        payload = run_gibbs(A, args, directed)

    if args.out_json:
        with open(args.out_json, "w") as fh:
            json.dump(payload, fh, indent=2)
        print(f"\nWrote {args.out_json}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
