def _soft_empty_note(q, label):
    """Warn if any hard class is empty (K likely over-specified), else ''."""
    counts = hard_cluster_counts(q)
    K = len(counts)
    empties = [type_labels(K)[k] for k in range(K) if counts[k] == 0]
    if not empties:
        return ""
    return (
        f"Note: hard class(es) {{{', '.join(empties)}}} are soft-empty in the "
        f"{label} fit (no node argmaxes onto them). K may be over-specified."
    )


def _print_constrained_block(con, K, infer_beta):
    print(f"\n=== Constrained SBM (Game-Theoretic, K={K}) ===")
    gauge_used = con.get("gauge", "pin_diag")
    if K == 2:
        a_val = float(con.get("a", con["payoff_matrix"][0, 0]))
        d_val = float(con.get("d", con["payoff_matrix"][1, 1]))
        diag_tag = "pinned" if gauge_used == "pin_diag" else "derived"
        print(f"Recovered payoffs: a={a_val:.4f} ({diag_tag}), b={con['b']:.4f}, "
              f"c={con['c']:.4f}, d={d_val:.4f} ({diag_tag})")
        print(f"Gauge: {gauge_used}  (a, d {diag_tag})")
        payoffs = [a_val, con["b"], con["c"], d_val]
        print(f"Graph type: {getGraphType(payoffs)[0]}")
        print(f"Game type:  {getGameType(payoffs)[0]}")
        # Fine-grained 2x2 label; taxonomy of Riedl & Smead (2026), Appendix
        # "Game Taxonomy and Role Labels".
        print(f"Game label: {game_label(*payoffs, with_roles=True)}")
    else:
        print("Recovered payoff matrix:")
        print(fmt_payoff_matrix(con["payoff_matrix"], con["pinned_diag"]))
        print(f"Gauge: {gauge_used}")
    beta_tag = "(inferred)" if infer_beta else "(fixed)"
    print(f"Inverse temperature: beta = {con['beta']:.4f} {beta_tag}")
    print(f"Population (soft mean, hard count): {fmt_freqs_with_counts(con['freqs'], con['q'])}")
    warn = _soft_empty_note(con["q"], "constrained")
    if warn:
        print(warn)
    print("\nJoint edge-type distribution M:")
    print(fmt_matrix(con["M"], K=K))
    print("\nEdge probability matrix B:")
    print(fmt_matrix(con["B"], K=K))


def _print_free_block(free, K):
    print(f"\n=== Free SBM (Unconstrained, K={K}) ===")
    print(f"Population (soft mean, hard count): {fmt_freqs_with_counts(free['pi'], free['q'])}")
    warn = _soft_empty_note(free["q"], "free")
    if warn:
        print(warn)
    print("B_free:")
    print(fmt_matrix(free["B"], K=K))


def _print_model_comparison(cmp_):
    """Pretty-print the MDL + Vuong comparison block."""
    print("\n=== Model Comparison (MDL / Vuong) ===")
    print("\nDescription length (MDL-BIC approximation):")
    print(f"  Constrained:  {cmp_['sigma_bic_constrained']:.2f} nats   (d={cmp_['d_constrained']})")
    print(f"  Free:         {cmp_['sigma_bic_free']:.2f} nats   (d={cmp_['d_free']})")
    db = cmp_["delta_bic"]
    side_b = "free preferred" if db > 0 else ("constrained preferred" if db < 0 else "tied")
    print(f"  ΔΣ_BIC (constrained − free): {db:+.2f} nats   ({kass_raftery_category(abs(db))}, {side_b})")

    if cmp_["laplace_valid"]:
        print("\nDescription length (MDL-Laplace approximation):")
        print(f"  Constrained:  {cmp_['sigma_laplace_constrained']:.2f} nats")
        print(f"  Free:         {cmp_['sigma_laplace_free']:.2f} nats")
        dl = cmp_["delta_laplace"]
        side_l = "free preferred" if dl > 0 else ("constrained preferred" if dl < 0 else "tied")
        print(f"  ΔΣ_Laplace (constrained − free): {dl:+.2f} nats   "
              f"({kass_raftery_category(abs(dl))}, {side_l})")
    else:
        print("\nDescription length (MDL-Laplace approximation):")
        print("  [skipped: Fisher information not positive definite at constrained optimum]")

    v = cmp_["vuong"]
    print("\nVuong test (in-sample):")
    if v.get("degenerate"):
        print("  V ≈ 0    p ≈ 1   (both models predict essentially identical probabilities)")
    else:
        Vc_str = f", V_corrected = {v['V_corrected']:+.3f}" if v["V_corrected"] is not None else ""
        print(f"  V = {v['V']:+.3f}   p = {v['p_value']:.4f}{Vc_str}")
        if v["p_value"] < 0.05:
            side = "constrained preferred" if v["V"] > 0 else "free preferred"
            print(f"  → significant at α = 0.05 ({side})")
        else:
            print("  → no significant difference at α = 0.05")

    print("\nInterpretation:")
    print("  ΔΣ < 0  →  game-theoretic model preferred (shorter description)")
    print("  ΔΣ > 0  →  free model preferred")
    print("  |ΔΣ| < 3 nats  →  models are practically indistinguishable")


def _print_delta_elpd(d):
    print("\nΔELPD_kfold (constrained − free):")
    print(f"  ΔELPD = {d['delta_elpd']:+.3f} nats   SE = {d['se']:.3f}   z = {d['z']:+.3f}")
    if d["se"] > 0:
        ratio = abs(d["delta_elpd"]) / d["se"]
        tag = ("reliable difference" if ratio > 4.0
               else "borderline (< 4.0 threshold)" if ratio > 2.0
               else "not reliable")
        print(f"  |ΔELPD| / SE = {ratio:.2f}  →  {tag}")
    print(f"  Per-fold Δ: [{', '.join(f'{x:+.2f}' for x in d['per_fold_deltas'])}]")


def _print_mcmc_diagnostics(name, result, param_labels, rhat_key, ess_key,
                            show_acceptance):
    """Chains/samples, optional MH acceptance, R-hat / ESS table."""
    print(f"\n--- {name} MCMC diagnostics ---")
    line = (f"  chains: {result.get('n_chains', '?')}    "
            f"samples/chain: {result.get('n_samples_per_chain', '?')}")
    if show_acceptance and "acceptance_rate" in result:
        line += f"    MH acceptance: {result['acceptance_rate']:.2%}"
    print(line)
    rh = result.get(rhat_key) or []
    ess = result.get(ess_key) or []
    if not rh:
        return
    print(f"  {'param':12s}  {'R-hat':>8s}  {'ESS':>8s}")
    for lbl, r_, e_ in zip(param_labels, rh, ess):
        rstr = f"{r_:8.3f}" if np.isfinite(r_) else "     nan"
        estr = f"{e_:8.0f}" if np.isfinite(e_) else "     nan"
        print(f"  {lbl:12s}  {rstr}  {estr}")
    bad = [param_labels[i] for i, v in enumerate(rh) if np.isfinite(v) and v >= 1.05]
    if bad:
        print(f"  Warning: R-hat ≥ 1.05 on {bad} — increase --n-samples or check mixing.")


def _print_posterior_summary(con, K):
    """Posterior payoff / frequency credible intervals for the constrained fit."""
    summary = con.get("posterior_summary")
    if summary is None:
        return
    print("\n=== Constrained posterior (Gibbs) ===")
    mean = summary["payoff_mean"]
    ci = summary["payoff_ci_95"]
    labels = (["c", "b"] if K == 2 and len(mean) == 2
              else [f"payoff[{i}]" for i in range(len(mean))])
    print("  Payoffs (mean [95% CI]):")
    for i, mu in enumerate(mean):
        print(f"    {labels[i]} = {mu:.4f}  [{ci[0, i]:.4f}, {ci[1, i]:.4f}]")
    fmean = summary["freq_mean"]
    fci = summary["freq_ci_95"]
    type_lbls = "XYZWVUTSRQ"[:K]
    print("  Frequencies (mean [95% CI]):")
    for k, lbl in enumerate(type_lbls):
        print(f"    {lbl} = {fmean[k]:.4f}  [{fci[0, k]:.4f}, {fci[1, k]:.4f}]")
    if con.get("infer_beta"):
        b_ci = summary["beta_ci_95"]
        print(f"  β posterior: mean {summary['beta_mean']:.4f}  "
              f"[95% CI {b_ci[0]:.4f}, {b_ci[1]:.4f}]")


