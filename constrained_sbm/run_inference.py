def run_em(A, args, directed):
    n = A.shape[0]
    E = num_directed_edges(A) if directed else num_undirected_edges(A)
    beta_arg = None if args.infer_beta else args.beta
    dc_tag = " [degree-corrected]" if args.degree_corrected else ""
    sweep_trace = None

    if args.beta_sweep:
        print(f"\n=== Beta sweep (Brent's method, beta in [{args.beta_low}, {args.beta_high}]) ===")
        con, sweep_trace = sweep_beta(
            A, K=args.K, beta_low=args.beta_low, beta_high=args.beta_high,
            n_restarts=args.restarts, seed=args.seed,
            degree_corrected=args.degree_corrected, theta_max=args.theta_max,
            max_iter=args.max_iter, tol=args.tol, verbose=args.verbose,
            gauge=args.gauge, directed=directed, n_spectral=args.n_spectral,
        )
        print(f"Evaluations: {len(sweep_trace)}")
        for bval, e in sorted(sweep_trace):
            marker = "  <- best" if abs(bval - con["beta"]) < 1e-9 else ""
            print(f"  beta={bval:7.4f}  ELBO={e:.4f}{marker}")
        print(f"Optimal beta: {con['beta']:.4f}")
        beta_arg = float(con["beta"])  # lock beta for everything downstream
    else:
        print(f"\nFitting constrained (game-theoretic) SBM, K={args.K}{dc_tag} ...")
        con = fit_constrained(
            A, K=args.K, beta=beta_arg, max_iter=args.max_iter, tol=args.tol,
            n_restarts=args.restarts, seed=args.seed, verbose=args.verbose,
            degree_corrected=args.degree_corrected, theta_max=args.theta_max,
            gauge=args.gauge, n_spectral=args.n_spectral, directed=directed,
        )
    print(f"Fitting free (unconstrained) SBM, K={args.K}{dc_tag} ...")
    free = fit_free(
        A, K=args.K, max_iter=args.max_iter, tol=args.tol,
        n_restarts=args.restarts, seed=args.seed, verbose=args.verbose,
        degree_corrected=args.degree_corrected, theta_max=args.theta_max,
        directed=directed,
        # Same restart schedule as the constrained fit, warm-started from its
        # converged (q, theta); the free B is the unconstrained MLE there, so
        # ELBO_free >= ELBO_constrained holds by construction.
        n_spectral=args.n_spectral,
        warm_start_q=con.get("q"),
        warm_start_theta=con.get("theta"),
    )

    # Orientation convention (K=2, pin_diag only; exact likelihood symmetry, so
    # nothing below changes except which block is called X). Default on.
    canon_swapped = False
    if args.canonicalize:
        _, canon_swapped = canonicalize_result(con)
        if canon_swapped:
            print("\n[orientation canonicalized: c/b <= a/d -> swapped X<->Y so X is the "
                  "more homophilous block; pass --no-canonicalize for the raw orientation]")

    _print_constrained_block(con, args.K, args.infer_beta)
    print(f"\nELBO: {con['elbo']:.4f}   Converged: {con['converged']} (iter {con['iterations']})")
    _print_free_block(free, args.K)
    print(f"ELBO: {free['elbo']:.4f}   Converged: {free['converged']} (iter {free['iterations']})")

    gap = con["elbo"] - free["elbo"]
    pct = 100.0 * gap / max(abs(free["elbo"]), 1.0)
    print("\n=== Comparison ===")
    print(f"ELBO gap (constrained - free): {gap:.4f}  ({pct:+.4f}%)")
    if args.degree_corrected:
        print("Note: DC ELBOs are on the Poisson scale; use --cv-folds for held-out metrics.")

    cmp_ = compute_model_comparison(
        A, con, free, K=args.K, infer_beta=args.infer_beta,
        degree_corrected=args.degree_corrected, directed=directed,
    )
    _print_model_comparison(cmp_)

    delta_elpd_result = None
    cv_result = None
    if args.cv_folds > 0:
        print(f"\nRunning {args.cv_folds}-fold cross-validation (delta ELPD) ...")
        cv_result = compare_models(
            A, n_folds=args.cv_folds, beta=beta_arg if beta_arg is not None else args.beta,
            n_restarts=args.restarts, seed=args.seed, verbose=False, K=args.K,
            degree_corrected=args.degree_corrected, gauge=args.gauge,
            n_spectral=args.n_spectral, max_iter=args.max_iter, tol=args.tol,
        )
        per_fold_c = [r["constrained_test_ll"] for r in cv_result["folds"]]
        per_fold_f = [r["free_test_ll"] for r in cv_result["folds"]]
        delta_elpd_result = compute_delta_elpd(per_fold_c, per_fold_f)
        _print_delta_elpd(delta_elpd_result)

    payload = {
        "method": "em", "K": args.K, "n": int(n), "num_edges": int(E),
        "directed": bool(directed),
        "constrained": {
            "payoff_matrix": con["payoff_matrix"].tolist(),
            "freqs": np.asarray(con["freqs"]).tolist(),
            "beta": con["beta"], "M": con["M"].tolist(), "B": con["B"].tolist(),
            "elbo": con["elbo"],
            "canonicalized": bool(args.canonicalize), "canonical_swapped": bool(canon_swapped),
        },
        "free": {"freqs": np.asarray(free["pi"]).tolist(), "B": free["B"].tolist(),
                 "elbo": free["elbo"]},
        "elbo_gap": gap,
        "model_comparison": cmp_,
        "delta_elpd": delta_elpd_result,
        "beta_sweep": None if sweep_trace is None else
                      {"beta_low": args.beta_low, "beta_high": args.beta_high,
                       "trace": [[float(x), float(y)] for x, y in sweep_trace],
                       "beta_opt": float(con["beta"])},
    }
    if args.K == 2:
        a_val = float(con.get("a", con["payoff_matrix"][0, 0]))
        d_val = float(con.get("d", con["payoff_matrix"][1, 1]))
        payload["constrained"].update(
            b=con["b"], c=con["c"], x=con["x"],
            game_label=game_label(a_val, con["b"], con["c"], d_val, with_roles=True),
        )
    return payload


