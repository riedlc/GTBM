"""CLI: fit the constrained (game-theoretic) and free SBM and report the
model-comparison diagnostics used in the paper.

Two estimators are available via --method:

    em     Variational EM. Reports recovered payoffs, M / B, the ELBO gap,
           the MDL / Vuong comparison, and (with --cv-folds N) the k-fold
           ΔELPD between the constrained and free models.

    gibbs  Full Bayesian Gibbs sampling. Reports posterior payoff / frequency
           credible intervals, MCMC R-hat / ESS, WAIC, and PSIS-LOO-CV
           (PSIS-LOO needs the optional `arviz` package; install with
           `pip install -e ".[loo]"`).

Examples
--------
Quick start on Zachary's karate club (built into networkx, no file needed):

    python -m constrained_sbm.run_inference --dataset zachary

Run on your own network (edgelist, .npz adjacency, or .graphml/.gml):

    python -m constrained_sbm.run_inference --input network.gml
"""

